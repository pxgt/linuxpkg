#!/usr/bin/env python3
"""Turns testdata/sign/ into MoonBit test fixtures.

sign/fixtures_test.mbt gets everything (keys, gpg's signatures, the test text);
the packages that sign things (repo, rpm, arch, apk, cmd/main) get the keys only,
so that their tests can sign without reaching into another package.
Run by make_sign_fixtures.sh; can be run alone to regenerate the .mbt files.
"""
import binascii
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..')
root = os.path.abspath(root)
d = os.path.join(root, 'testdata', 'sign')
HEADER = ['///|', '/// Generated by tools/oracle/make_sign_fixtures.sh from testdata/sign/. Test-only keys.', '']


def text(out, name, var):
    s = open(os.path.join(d, name), newline='').read()
    out.append('///|')
    out.append('let %s : String =' % var)
    for line in s.split('\n')[:-1]:
        out.append('  #|' + line)
    out.append('')


def binary(out, name, var):
    h = binascii.hexlify(open(os.path.join(d, name), 'rb').read()).decode()
    out.append('///|')
    out.append('let %s : String =' % var)
    for i in range(0, len(h), 96):
        out.append('  #|' + h[i:i + 96])
    out.append('')


def write(path, out):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', newline='\n').write('\n'.join(out) + '\n')


out = list(HEADER)
text(out, 'data.txt', 'fx_data')
for n, v in (('rsa2048', 'rsa'), ('ed25519', 'ed'), ('locked', 'locked')):
    text(out, 'test-only-%s.sec.asc' % n, 'fx_%s_secret' % v)
    if n != 'locked':
        text(out, 'test-only-%s.pub.asc' % n, 'fx_%s_public' % v)
for n, v in (('rsa2048', 'rsa'), ('ed25519', 'ed')):
    text(out, 'gpg-%s.sig.asc' % n, 'fx_%s_sig_armored' % v)
    binary(out, 'gpg-%s.sig' % n, 'fx_%s_sig_hex' % v)
    text(out, 'gpg-%s.clearsigned.asc' % n, 'fx_%s_clearsigned' % v)
write(os.path.join(root, 'sign', 'fixtures_test.mbt'), out)

# Which keys each signing package's tests use (an unused fixture is a warning).
USES = {'repo': ['ed'], 'cmd/main': ['ed']}
NAMES = {'rsa': 'rsa2048', 'ed': 'ed25519'}
for pkg, which in USES.items():
    if not os.path.isdir(os.path.join(root, pkg)):
        continue
    keys = list(HEADER)
    for v in which:
        text(keys, 'test-only-%s.sec.asc' % NAMES[v], 'fx_%s_secret' % v)
        text(keys, 'test-only-%s.pub.asc' % NAMES[v], 'fx_%s_public' % v)
    # main packages keep their tests white-box (private functions, one test world)
    suffix = 'wbtest' if pkg == 'cmd/main' else 'test'
    write(os.path.join(root, pkg, 'sign_fixtures_%s.mbt' % suffix), keys)
print('wrote sign/fixtures_test.mbt and the key fixtures of the other packages')
