#!/usr/bin/env python3
"""Writes elf/samples_test.mbt: the sample files of testdata/elf as base64, with what readelf says
about each of them, so that the tests compare the reader with readelf without running it.

usage: samples_to_mbt.py [TESTDATA_DIR] > elf/samples_test.mbt   (needs readelf)
"""
import base64
import os
import re
import subprocess
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "testdata/elf"


def readelf(path, flag):
    return subprocess.run(["readelf", flag, "-W", path], capture_output=True, text=True, check=True).stdout


def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


print("// Generated by tools/elf/samples_to_mbt.py from testdata/elf; do not edit.")
print()
print("///|")
print("let samples : Array[(String, String, Int32, Bool, String?, Array[String])] = [")
for name in sorted(os.listdir(root)):
    if name.endswith((".c", ".md")):
        continue
    path = os.path.join(root, name)
    header, program, dynamic = readelf(path, "-h"), readelf(path, "-l"), readelf(path, "-d")
    bits = 32 if re.search(r"Class:\s+ELF32", header) else 64
    little = "little endian" in re.search(r"Data:\s+(.*)", header).group(1)
    interp = re.search(r"Requesting program interpreter: (.*?)\]", program)
    needed = re.findall(r"\(NEEDED\)\s+Shared library: \[(.*?)\]", dynamic)
    data = base64.b64encode(open(path, "rb").read()).decode()
    interp_text = f"Some({quote(interp.group(1))})" if interp else "None"
    needed_text = "[" + ", ".join(quote(n) for n in needed) + "]"
    print(f"  ({quote(name)}, {quote(data)}, {bits}, {'true' if little else 'false'}, {interp_text}, {needed_text}),")
print("]")
